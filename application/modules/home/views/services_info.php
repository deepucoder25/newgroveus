<!-- Interactive Tab Navigation & 30s Auto-Cycle -->
<script>
(function() {
  const root = document.getElementById('whiteLabelServices');
  if (!root) return;

  const tabs = root.querySelectorAll('.wl-tab-box');
  const panels = root.querySelectorAll('.wl-panel');
  let current = 0;
  let timer = null;
  let locked = false;

  function showTab(idx, isUser = false) {
    if (isUser) { locked = true; clearInterval(timer); }
    current = (idx + tabs.length) % tabs.length;
    tabs.forEach((t, i) => {
      const active = i === current;
      t.classList.toggle('active', active);
      t.setAttribute('aria-selected', active);
      if (active) t.scrollIntoView({ behavior: 'smooth', block: 'nearest', inline: 'center' });
    });
    panels.forEach((p, i) => p.classList.toggle('active', i === current));
  }

  function startTimer() {
    if (locked) return;
    clearInterval(timer);
    timer = setInterval(() => showTab(current + 1), 30000);
  }

  tabs.forEach((t, i) => t.addEventListener('click', () => showTab(i, true)));
  root.querySelector('#wlArrowPrev')?.addEventListener('click', () => showTab(current - 1, true));
  root.querySelector('#wlArrowNext')?.addEventListener('click', () => showTab(current + 1, true));
  root.querySelector('#wlContentStage')?.addEventListener('click', () => { locked = true; clearInterval(timer); });
  root.addEventListener('mouseenter', () => clearInterval(timer));
  root.addEventListener('mouseleave', startTimer);

  startTimer();
})();
</script>
